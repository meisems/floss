// Bundles migrations/*.sql into src/generated/migrations.ts so the Worker can apply its own schema
// to an auto-provisioned D1 database (no console step). Runs as part of `npm run build`.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const files = readdirSync("migrations").filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const migrations = files.map((name) => ({
  name,
  statements: readFileSync(`migrations/${name}`, "utf8")
    .split("\n")
    .filter((l) => !l.trimStart().startsWith("--"))
    .join("\n")
    .split(/;\s*$/m)
    .map((s) => s.trim())
    .filter(Boolean),
}));

mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/migrations.ts",
  `// Generated by scripts/embed-migrations.mjs from migrations/*.sql. Do not edit.\n` +
    `export const MIGRATIONS: ReadonlyArray<{ name: string; statements: readonly string[] }> = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`embedded ${files.length} migrations: ${files.join(", ")}`);
